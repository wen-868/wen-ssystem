SELECT VERSION() AS version, @@character_set_server AS cs, @@collation_server AS coll;
SELECT COUNT(*) AS tables FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_TYPE='BASE TABLE';
SELECT COUNT(*) AS columns_total FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE();
SELECT TABLE_NAME, ORDINAL_POSITION, COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT, CHARACTER_SET_NAME, COLLATION_NAME, EXTRA
  FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE()
 ORDER BY TABLE_NAME, ORDINAL_POSITION;
